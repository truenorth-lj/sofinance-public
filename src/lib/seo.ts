import type { Metadata } from "next";
import { docsPageBySlug, type DocsSlug } from "@/lib/docs-nav";
import { getCanonicalSiteUrl } from "@/lib/public-urls";

export const SITE_NAME = "SoFinance";
export const SITE_X_HANDLE = "@SoFinancelab";
/** Title template applied by the root layout to every child page's `title`. */
export const SITE_TITLE_TEMPLATE = `%s · ${SITE_NAME}`;
export const SITE_DEFAULT_TITLE = "SoFinance: collect trading fees on tokenized stocks";
export const SITE_DEFAULT_DESCRIPTION =
  "Pair two issuers' tokens of the same stock in one liquidity pool and collect trading fees. Self-custodial: you sign every transaction in your own wallet.";

/**
 * Site-wide share card: a static 1200x630 PNG in /public (no per-request rendering). Generated by
 * `pnpm og:image` (scripts/generate-og-image.mjs). Never put APR or other live numbers on it.
 */
export const OG_IMAGE = {
  url: "/og.png",
  width: 1200,
  height: 630,
  alt: "SoFinance: collect trading fees on tokenized stocks. Self-custodial on Solana and Robinhood Chain.",
} as const;

/** Absolute site origin for `metadataBase` (NEXT_PUBLIC_APP_URL when set, else production). */
export function siteMetadataBase(): URL {
  return new URL(getCanonicalSiteUrl());
}

type PageSeo = {
  /** Page title without the brand suffix (the root template adds " · SoFinance"). */
  title: string;
  description: string;
  /** Root-relative canonical path, e.g. "/docs/fee-apr". */
  path: string;
  /** Skip the template: use the title as-is. */
  absoluteTitle?: boolean;
};

/** Title, description, canonical, Open Graph and Twitter card for one public page. */
export function pageMetadata({ title, description, path, absoluteTitle }: PageSeo): Metadata {
  const shareTitle = absoluteTitle ? title : `${title} · ${SITE_NAME}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title: shareTitle,
      description,
      images: [{ ...OG_IMAGE }],
    },
    twitter: {
      card: "summary_large_image",
      site: SITE_X_HANDLE,
      title: shareTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}

export function docsPageMetadata(slug: DocsSlug): Metadata {
  const page = docsPageBySlug(slug);
  return pageMetadata({ title: page.metaTitle, description: page.metaDescription, path: page.href });
}
